function point(number: number): BoothMapPoint {
  const measured = MEASURED_CENTERS[number];
  if (measured) return { number, x: measured[0] / 1510, y: measured[1] / 1632 };
  let x = 0, y = 0;
  if (number >= 3 && number <= 11) { x = 799; y = 1047 + (number - 3) * 42; }
  else if (number >= 12 && number <= 19) { x = 864 + ((number - 12) % 4) * 43; y = 975 + Math.floor((number - 12) / 4) * 42; }
  else if (number >= 20 && number <= 25) { x = 864 + ((number - 20) % 3) * 43; y = 1074 + Math.floor((number - 20) / 3) * 42; }
  else if (number >= 26 && number <= 35) { x = 844 + (number - 26) * 42.5; y = 908; }
  else if (number >= 36 && number <= 38) { x = 570 + (number - 36) * 43; y = 1110; }
  else if (number >= 39 && number <= 46) { x = 550 + ((number - 39) % 4) * 43; y = number < 43 ? 1178 : 1234; }
  else if (number >= 47 && number <= 51) { x = 509 + (number - 47) * 43; y = 1354; }
  else if (number >= 52 && number <= 60) { x = 738; y = 1338 - (number - 52) * 42; }
  else if (number >= 61 && number <= 62) { x = 301 + (number - 61) * 43; y = 1387; }
  else if (number >= 63 && number <= 80) { x = 550 + ((number - 63) % 9) * 43; y = number < 72 ? 438 : 479; }
  return { number, x: x / 1510, y: y / 1632 };
}
export function getBoothMapLocation(name: string): BoothMapLocation | null {
  const special = SPECIAL_LOCATIONS[name.trim()];
  if (special) return special;
  const numbers = MAP_NUMBERS[name.trim()];
  if (numbers === undefined) return null;
  if (numbers === null) return { points: [{ number: null, x: 1062 / 1510, y: 987 / 1632 }], label: "과학기술관 앞 미디어센터 차량" };
  return { points: numbers.map(point), label: numbers.join("·") + "번 부스" };
}
